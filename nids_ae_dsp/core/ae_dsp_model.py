# =============================================================================
# 1. AE-DSP AutoEncoder Architecture (Official Repo Implementation)
# =============================================================================

class AutoEncoder(nn.Module):
    """
    Exact AutoEncoder architecture from AE-DSP manuscript and repository:
    `experiments/nsl_kdd/run_p6_final_zeroday_sensitive_system.py`
    and `experiments/cicids2017/run_p8a_cicids2017_heldout_validation.py`.
    """

    def __init__(
        self,
        input_dim: int,
        latent_dim: int = 8,
        hidden_dim: int = 64,
        dropout: float = 0.05,
    ) -> None:
        super().__init__()
        self.input_dim = input_dim
        self.latent_dim = latent_dim
        self.hidden_dim = hidden_dim

        h1 = max(hidden_dim, input_dim * 2, latent_dim * 4)
        h2 = max(hidden_dim // 2, latent_dim * 2)

        self.encoder = nn.Sequential(
            nn.Linear(input_dim, h1),
            nn.BatchNorm1d(h1),
            nn.ReLU(),
            nn.Dropout(dropout),
            nn.Linear(h1, h2),
            nn.BatchNorm1d(h2),
            nn.ReLU(),
            nn.Linear(h2, latent_dim),
        )
        self.decoder = nn.Sequential(
            nn.Linear(latent_dim, h2),
            nn.ReLU(),
            nn.Linear(h2, h1),
            nn.ReLU(),
            nn.Linear(h1, input_dim),
        )

    def forward(self, x: torch.Tensor) -> Tuple[torch.Tensor, torch.Tensor]:
        """
        Forward pass.
        Returns:
            recon: Reconstructed tensor in contribution space (same shape as x)
            z: Latent representation bottleneck tensor (shape: [batch_size, latent_dim])
        """
        z = self.encoder(x)
        recon = self.decoder(z)
        return recon, z


# =============================================================================
# 2. Representation Dataclass
# =============================================================================

@dataclass
class AEDSPRepresentation:
    """
    Rich feature representation generated by the Pretrained AE-DSP framework.
    Passed downstream to the Classifier and Anomaly Detector.
    """
    # 1. Latent embedding from AE bottleneck
    latent: np.ndarray  # shape: [batch_size, latent_dim]

    # 2. AE reconstruction outputs and residuals
    reconstruction: np.ndarray  # shape: [batch_size, topk]
    residuals_squared: np.ndarray  # shape: [batch_size, topk]
    ae_score: np.ndarray  # scalar mean reconstruction error, shape: [batch_size]
    ae_z: np.ndarray  # robust z-score deviation from normal manifold, shape: [batch_size]

    # 3. DSP Prototype metrics
    delta_shap: np.ndarray  # shape: [batch_size, topk]
    prototype_distances: np.ndarray  # shape: [batch_size, K]
    prototype_similarities: np.ndarray  # shape: [batch_size, K]
    nearest_proto_id: np.ndarray  # index of closest attack prototype, shape: [batch_size]
    nearest_proto_dist: np.ndarray  # distance to closest prototype, shape: [batch_size]
    dsp_score: np.ndarray  # raw similarity score, shape: [batch_size]
    dsp_z: np.ndarray  # robust z-score of prototype similarity, shape: [batch_size]

    # 4. Official Fusion Score
    fusion_score: np.ndarray  # alpha * ae_z + gamma * dsp_z, shape: [batch_size]

    # 5. Unified representation vector suitable for downstream heads
    fused_features: np.ndarray  # shape: [batch_size, rep_dim]

    def __len__(self) -> int:
        return len(self.latent)

    def get_sample(self, idx: int) -> Dict[str, Any]:
        """Extract a single sample representation as a dict."""
        return {
            "latent": self.latent[idx],
            "ae_score": float(self.ae_score[idx]),
            "ae_z": float(self.ae_z[idx]),
            "nearest_proto_id": int(self.nearest_proto_id[idx]),
            "nearest_proto_dist": float(self.nearest_proto_dist[idx]),
            "dsp_score": float(self.dsp_score[idx]),
            "dsp_z": float(self.dsp_z[idx]),
            "fusion_score": float(self.fusion_score[idx]),
            "prototype_similarities": self.prototype_similarities[idx],
            "fused_features": self.fused_features[idx],
        }


