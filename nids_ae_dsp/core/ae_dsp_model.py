# 3. AE-DSP Core Foundation (Trained via Official AE-DSP Methodology)
# =============================================================================

class AEDSPFoundation:
    """
    AE-DSP Core Foundation model wrapper, trained following the official
    AE-DSP methodology (https://github.com/Feiyu0Li/AE-DSP).
    Encapsulates:
      - Feature preprocessor (OHE + Standard scaling)
      - TreeSHAP model and explainer (LightGBM)
      - Global Top-k SHAP feature selector
      - Trained PyTorch AutoEncoder on normal manifold
      - AE Robust z-score scalers (median, IQR)
      - DSP Attack Prototype KMeans (K=12) and similarity bandwidth (sigma)
      - DSP Robust z-score scalers (median, IQR)
      - Fusion parameters (alpha=0.8, gamma=1.8, target FPR threshold)
    """

    def __init__(
        self,
        autoencoder: AutoEncoder,
        ae_scaler: StandardScaler,
        top_idx: np.ndarray,
        mu_normal: np.ndarray,
        std_normal: np.ndarray,
        dsp_kmeans: KMeans,
        dsp_sigma: float,
        ae_med: float,
        ae_scale: float,
        dsp_med: float,
        dsp_scale: float,
        threshold: float,
        alpha: float = 0.8,
        gamma: float = 1.8,
        preprocessor: Optional[Any] = None,
        base_tree_model: Optional[Any] = None,
        feature_names: Optional[List[str]] = None,
        device: str = "cpu",
    ) -> None:
        self.device = device
        self.autoencoder = autoencoder.to(self.device)
        self.autoencoder.eval()
        self.ae_scaler = ae_scaler
        self.top_idx = np.asarray(top_idx, dtype=np.int64)
        self.mu_normal = np.asarray(mu_normal, dtype=np.float32)
        self.std_normal = np.asarray(std_normal, dtype=np.float32)
        self.dsp_kmeans = dsp_kmeans
        self.dsp_sigma = float(dsp_sigma)
        self.ae_med = float(ae_med)
        self.ae_scale = float(ae_scale)
        self.dsp_med = float(dsp_med)
        self.dsp_scale = float(dsp_scale)
        self.threshold = float(threshold)
        self.alpha = float(alpha)
        self.gamma = float(gamma)
        self.preprocessor = preprocessor
        self.base_tree_model = base_tree_model
        self.feature_names = feature_names or []
        self._tree_explainer = None

    @property
    def latent_dim(self) -> int:
        return self.autoencoder.latent_dim

    @property
    def topk(self) -> int:
        return len(self.top_idx)

    @property
    def proto_k(self) -> int:
        return self.dsp_kmeans.cluster_centers_.shape[0]

    @property
    def representation_dim(self) -> int:
        # latent_dim + proto_k + ae_z + dsp_z + nearest_proto_dist + fusion_score
        return self.latent_dim + self.proto_k + 4

    def _get_explainer(self):
        if self._tree_explainer is None and self.base_tree_model is not None:
            if shap is None:
                raise ImportError("SHAP is required for TreeSHAP extraction. Install with pip install shap.")
            self._tree_explainer = shap.TreeExplainer(self.base_tree_model)
        return self._tree_explainer

    def extract_positive_class_shap(self, shap_values: Any) -> np.ndarray:
        """Extract positive class SHAP values following AE-DSP repo convention."""
        if isinstance(shap_values, list):
            if len(shap_values) == 2:
                return np.asarray(shap_values[1], dtype=np.float32)
            return np.asarray(shap_values[0], dtype=np.float32)
        arr = np.asarray(shap_values)
        if arr.ndim == 3 and arr.shape[-1] == 2:
            arr = arr[:, :, 1]
        return np.asarray(arr, dtype=np.float32)

    def compute_shap_from_preprocessed(self, X_pre: np.ndarray, batch_size: int = 2048) -> np.ndarray:
        """Compute TreeSHAP vectors using the trained base tree model."""
        explainer = self._get_explainer()
        if explainer is None:
            raise ValueError("No base tree model configured in PretrainedAEDSP to compute SHAP values.")
        parts = []
        for start in range(0, X_pre.shape[0], batch_size):
            end = min(start + batch_size, X_pre.shape[0])
            sv = explainer.shap_values(X_pre[start:end])
            parts.append(self.extract_positive_class_shap(sv))
        return np.vstack(parts).astype(np.float32)

    def preprocess_raw(self, X_raw: Union[pd.DataFrame, np.ndarray]) -> np.ndarray:
        """Preprocess raw network flow inputs through the saved preprocessor."""
        if self.preprocessor is None:
            return np.asarray(X_raw, dtype=np.float32)
        transformed = self.preprocessor.transform(X_raw)
        if hasattr(transformed, "toarray"):
            transformed = transformed.toarray()
        return np.asarray(transformed, dtype=np.float32)

    @torch.no_grad()
    def extract_representation(
        self,
        X_or_shap: np.ndarray,
        is_already_shap: bool = False,
    ) -> AEDSPRepresentation:
        """
        Extract full AE-DSP representation:
          1. Project into Global Top-k SHAP space.
          2. Compute AE reconstruction residuals and latent representation z.
          3. Compute DeltaSHAP and DSP prototype distances and similarities.
          4. Compute robust AE_z and DSP_z scores and fusion score.
          5. Construct unified downstream feature representation.
        """
        if is_already_shap:
            shap_full = np.asarray(X_or_shap, dtype=np.float32)
        else:
            if self.base_tree_model is not None and self.preprocessor is not None and not isinstance(X_or_shap, np.ndarray):
                X_pre = self.preprocess_raw(X_or_shap)
                shap_full = self.compute_shap_from_preprocessed(X_pre)
            elif self.base_tree_model is not None:
                shap_full = self.compute_shap_from_preprocessed(np.asarray(X_or_shap, dtype=np.float32))
            else:
                shap_full = np.asarray(X_or_shap, dtype=np.float32)

        # Select Global Top-k SHAP features
        if shap_full.shape[1] > len(self.top_idx):
            X_topk = shap_full[:, self.top_idx]
        else:
            X_topk = shap_full

        batch_size = X_topk.shape[0]

        # 1. AE branch: Scale Top-k and pass through PyTorch AutoEncoder
        X_ae_scaled = self.ae_scaler.transform(X_topk).astype(np.float32)
        x_tensor = torch.tensor(X_ae_scaled, dtype=torch.float32, device=self.device)
        self.autoencoder.eval()
        recon_tensor, z_tensor = self.autoencoder(x_tensor)

        z = z_tensor.cpu().numpy()
        recon = recon_tensor.cpu().numpy()
        res2 = (recon - X_ae_scaled) ** 2
        ae_score = np.mean(res2, axis=1).astype(np.float64)

        # Robust z-score for AE
        ae_z = (ae_score - self.ae_med) / (self.ae_scale + 1e-12)

        # 2. DSP branch: Compute DeltaSHAP and prototype distances
        delta_shap = ((X_topk - self.mu_normal) / (self.std_normal + 1e-8)).astype(np.float32)
        centers = self.dsp_kmeans.cluster_centers_.astype(np.float32)  # [K, topk]

        # Pairwise distance to all prototypes: [batch_size, K]
        # delta_shap[:, None, :] shape [B, 1, topk], centers[None, :, :] shape [1, K, topk]
        diffs = delta_shap[:, None, :] - centers[None, :, :]
        d2 = np.sum(diffs ** 2, axis=2)  # [B, K]
        proto_distances = np.sqrt(np.maximum(d2, 0.0)).astype(np.float64)

        nearest_proto_id = np.argmin(proto_distances, axis=1).astype(np.int64)
        nearest_proto_dist = proto_distances[np.arange(batch_size), nearest_proto_id]

        # Prototype similarity kernel
        proto_similarities = np.exp(-proto_distances / (self.dsp_sigma + 1e-8)).astype(np.float64)
        dsp_score = np.exp(-nearest_proto_dist / (self.dsp_sigma + 1e-8)).astype(np.float64)

        # Robust z-score for DSP
        dsp_z = (dsp_score - self.dsp_med) / (self.dsp_scale + 1e-12)

        # 3. Fusion Score (official formula)
        fusion_score = (self.alpha * ae_z + self.gamma * dsp_z).astype(np.float64)

        # 4. Unified downstream feature vector for the Classifier
        # Concatenate: [z (latent_dim), proto_similarities (K), ae_z (1), dsp_z (1), nearest_dist (1), fusion_score (1)]
        fused_features = np.hstack([
            z,
            proto_similarities,
            ae_z[:, None],
            dsp_z[:, None],
            nearest_proto_dist[:, None],
            fusion_score[:, None],
        ]).astype(np.float32)

        return AEDSPRepresentation(
            latent=z,
            reconstruction=recon,
            residuals_squared=res2,
            ae_score=ae_score,
            ae_z=ae_z,
            delta_shap=delta_shap,
            prototype_distances=proto_distances,
            prototype_similarities=proto_similarities,
            nearest_proto_id=nearest_proto_id,
            nearest_proto_dist=nearest_proto_dist,
            dsp_score=dsp_score,
            dsp_z=dsp_z,
            fusion_score=fusion_score,
            fused_features=fused_features,
        )


# Backward-compatibility alias
PretrainedAEDSP = AEDSPFoundation
